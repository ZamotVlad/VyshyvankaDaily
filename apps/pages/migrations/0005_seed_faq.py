def create_faq(apps, schema_editor):
    FAQCategory = apps.get_model("pages", "FAQCategory")
    FAQItem = apps.get_model("pages", "FAQItem")

    category, _ = FAQCategory.objects.get_or_create(
        name="Загальні питання", defaults={"order": 1}
    )
    for order, (question, answer) in enumerate(FAQ_ITEMS, start=1):
        FAQItem.objects.get_or_create(
            category=category,
            question_uk=question,
            defaults={"answer_uk": answer, "order": order},
        )


