def rewrite_faq(apps, schema_editor):
    FAQCategory = apps.get_model("pages", "FAQCategory")
    FAQItem = apps.get_model("pages", "FAQItem")

    FAQCategory.objects.filter(name=OLD_CATEGORY).delete()

    for name, order, items in NEW_FAQ:
        category, _ = FAQCategory.objects.get_or_create(
            name=name, defaults={"order": order}
        )
        for item_order, (question, answer) in enumerate(items, start=1):
            FAQItem.objects.get_or_create(
                category=category,
                question_uk=question,
                defaults={
                    "question": question,
                    "answer": answer,
                    "answer_uk": answer,
                    "order": item_order,
                },
            )


