def _render_motif_in_zone(motif: Motif, zone: dict, colors: list[str]) -> str:
    """
    Диспетчер за форматом geometry_parameters (ADR 39):
    - "pixel_grid_v1" — піксельна сітка (основний формат, render_grid_in_zone);
    - легасі base_points+symmetry — полігональний тайлінг (лишається як
      запобіжник для записів, ще не переведених міграцією 0012).
    """
    geometry = motif.geometry_parameters
    if geometry.get("format") == "pixel_grid_v1":
        return render_grid_in_zone(geometry, zone, colors)
    return _render_polygon_motif_in_zone(motif, zone, colors[0])


def _render_polygon_motif_in_zone(motif: Motif, zone: dict, fill_color: str) -> str:
    geometry = motif.geometry_parameters
    shapes = apply_symmetry(
        geometry["base_points"], geometry["symmetry"], geometry.get("params", {})
    )

    all_points = [p for shape in shapes for p in shape]
    xs = [p[0] for p in all_points]
    ys = [p[1] for p in all_points]
    span_x = max(max(xs) - min(xs), 1)
    span_y = max(max(ys) - min(ys), 1)

    horizontal = zone["width"] >= zone["height"]
    long_side = zone["width"] if horizontal else zone["height"]
    short_side = zone["height"] if horizontal else zone["width"]
    tiles = max(1, round(long_side / short_side))
    cell_w = zone["width"] / tiles if horizontal else zone["width"]
    cell_h = zone["height"] if horizontal else zone["height"] / tiles

    polygons = []
    for t in range(tiles):
        cx = zone["x"] + (t * cell_w if horizontal else 0)
        cy = zone["y"] + (0 if horizontal else t * cell_h)
        for shape in shapes:
            scaled = [
                (
                    cx + (x - min(xs)) / span_x * cell_w,
                    cy + (y - min(ys)) / span_y * cell_h,
                )
                for x, y in shape
            ]
            coords = " ".join(f"{x:.2f},{y:.2f}" for x, y in scaled)
            polygons.append(f'<polygon points="{coords}" fill="{fill_color}" />')

    return "".join(polygons)


def render_pattern_svg(region: Region, motifs: list[Motif], cut: str = "standard") -> str:
    """
    SVG орнаменту дня (розділ 8.5, 8.7 ТЗ): контур вишиванки + мотиви
    на зонах (знову ввімкнено — ADR 39, алгоритм версії 2).

    Розподіл мотивів детермінований, без rng у рендері:
    - motifs[0] (головний) -> placket;
    - motifs[1] (або [0], якщо мотив один) -> collar і обидві манжети;
    - motifs[2], якщо є -> collar (замість [1]), щоб комір і манжети
      відрізнялись у регіонів із трьома мотивами.
    Усі зони лежать на тканині, тому всі мотиви малюються ПІД контуром;
    лінія розрізу пазухи — окремим елементом поверх.
    """
    shirt = SHIRT_CUT_REGISTRY[cut]
    zones = shirt["embroidery_zones"]
    slit = shirt["placket_slit"]
    colors = build_ornament_palette(region.dominant_colors)

    primary = motifs[0] if motifs else None
    secondary = motifs[1] if len(motifs) > 1 else primary
    collar_motif = motifs[2] if len(motifs) > 2 else secondary

    motif_markup = ""
    if primary is not None:
        motif_markup += _render_motif_in_zone(primary, zones["placket"], colors)
        motif_markup += _render_motif_in_zone(collar_motif, zones["collar"], colors)
        motif_markup += _render_motif_in_zone(secondary, zones["cuff_left"], colors)
        motif_markup += _render_motif_in_zone(secondary, zones["cuff_right"], colors)

    return (
        f'<svg viewBox="{shirt["viewbox"]}" xmlns="http://www.w3.org/2000/svg" '
        f'role="img" aria-label="Орнамент {region.name}">'
        f'<path d="{shirt["body"]}" fill="#FFFFFF"/>'
        f"{motif_markup}"
        f'<path d="{shirt["outline"]}" fill="{shirt["outline_fill"]}" fill-rule="evenodd"/>'
        f'<line x1="{slit["x"]}" y1="{slit["y1"]}" x2="{slit["x"]}" y2="{slit["y2"]}" '
        f'stroke="{shirt["outline_fill"]}" stroke-width="{slit["width"]}"/>'
        f"</svg>"
    )
